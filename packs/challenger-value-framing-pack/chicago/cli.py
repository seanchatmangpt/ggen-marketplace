def main():
    repo_path = "/Users/sac/ggen-marketplace"
    try:
        import subprocess
        commit_sha = subprocess.check_output(["git", "-C", repo_path, "rev-parse", "HEAD"]).decode().strip()
    except Exception:
        commit_sha = "0000000000000000000000000000000000000000"

    out_dir = os.path.join(os.path.dirname(__file__), "output")
    os.makedirs(out_dir, exist_ok=True)
    profiles = build_benchmark_profiles()

    print(f"[*] Running Chicago Challenger Sales Engine with Substrate Benchmarks over {len(profiles)} archetypes...")
    for prof in profiles:
        audit = ChallengerCompiler.compile(prof)
        slug = prof.company_name.lower().replace(" ", "_").replace("&", "and")
        md_path = os.path.join(out_dir, f"audit_{slug}.md")
        receipt_path = os.path.join(out_dir, f"receipt_{slug}.json")

        md_content = format_audit_markdown(audit)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        receipt = generate_dfcm_receipt(audit, md_path, repo_path, commit_sha)
        with open(receipt_path, "w", encoding="utf-8") as f:
            json.dump(receipt, f, indent=2)

        print(f" -> Compiled: {prof.company_name} | Drag: ${audit.total_dollar_drag:,.2f}/yr | Substrate: {audit.proof.substrate_claim.component}")

    print("[*] All audits compiled with verified benchmark claims.")

if __name__ == "__main__":
    main()
