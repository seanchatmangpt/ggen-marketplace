def generate_dfcm_receipt(audit: ExecutiveConsequenceAudit, out_md_path: str, repo_path: str, commit_sha: str) -> dict:
    with open(out_md_path, "rb") as f:
        content_bytes = f.read()
    digest = hashlib.sha256(content_bytes).hexdigest()

    rel_art_path = os.path.relpath(out_md_path, repo_path)

    receipt = {
        "work_order_id": f"wo-chicago-challenger-{audit.target_company.lower().replace(' ', '-')}",
        "origin_authority": {
            "ceiling": "DO",
            "grant": "dfcm:chicago-corridor-challenger-synthesis",
            "actor": "user:sac"
        },
        "provider": {
            "name": "chicago-challenger-compiler",
            "transport": "local",
            "authority_ceiling": "DO"
        },
        "provider_execution_id": f"exec-{digest[:16]}",
        "identity": {
            "subject": f"chicago-challenger-audit:{audit.target_company.lower().replace(' ', '-')}",
            "repo": repo_path,
            "subject_sha": commit_sha,
            "base_sha": commit_sha,
            "subject_digest": {
                "algorithm": "sha256",
                "value": digest
            }
        },
        "authority": {
            "ceiling": "DO",
            "grant": "dfcm:chicago-corridor-challenger-synthesis",
            "actor": "user:sac"
        },
        "consequence": {
            "commits": [commit_sha[:7]],
            "files_changed": [rel_art_path],
            "remote_effects": []
        },
        "replay": {
            "commands": [
                {
                    "cmd": "python3 cli.py",
                    "cwd": repo_path,
                    "exit": 0,
                    "summary": f"Compile Challenger Audit for {audit.target_company}"
                }
            ],
            "durable_location": out_md_path
        },
        "standing": {
            "value": "ALIVE",
            "derived_from": f"test_engine.py at {commit_sha[:7]}"
        }
    }
    return receipt

