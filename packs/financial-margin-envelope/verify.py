#!/usr/bin/env python3
"""Chicago verifier for financial-margin-envelope.

1. Run every gates/*.rq SELECT against ontology.ttl; rows = violation; exit 1
   on any violation.
2. Anti-vacuity court: mutate the graph (raise the quote so margin drops below
   the floor) and PROVE gate 030 flips to violation. A gate that cannot flip
   fails the verifier as VACUOUS GATE.
3. Spot-check the generated module: it exists, carries the generated marker,
   names every refusal atom in the closed vocabulary, and has fail-closed
   clauses; and `elixir -e` evaluates admit/1 on the rendered positive control
   when a real elixir runtime is available.
"""
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Iterable, cast

from rdflib import Graph

PACK_DIR = Path(__file__).resolve().parent
ONT = PACK_DIR / "ontology.ttl"


def run_gates(graph: Graph) -> int:
    violations = 0
    for gate in sorted((PACK_DIR / "gates").glob("*.rq")):
        query = gate.read_text(encoding="utf-8")
        rows = list(cast(Iterable[tuple], graph.query(query)))
        if rows:
            violations += len(rows)
            print(f"VIOLATION {gate.name}: {len(rows)} row(s)")
            for row in rows:
                print(f"  {tuple(str(c) for c in row)}")
        else:
            print(f"PASS {gate.name}: 0 rows")
    return violations


def anti_vacuity_court() -> bool:
    """Mutate: raise quote 180000 -> 220000. Margin (250000-220000)/250000
    = 0.12 < 0.22 floor, so gate 030 MUST flip to >= 1 row."""
    graph = Graph()
    graph.parse(ONT, format="turtle")
    from rdflib import URIRef, Literal
    from rdflib.namespace import XSD

    mutated = 0
    for s, p, o in graph.triples(
        (URIRef("urn:fin:margin-envelope:env-001-qamt"),
         URIRef("urn:fin:margin-envelope:decimalValue"), None)
    ):
        graph.remove((s, p, o))
        graph.add((s, p, Literal("220000.00", datatype=XSD.decimal)))
        mutated += 1
    if mutated == 0:
        print("VACUOUS COURT: mutation target not found; mutation never ran")
        return False

    gate = (PACK_DIR / "gates" / "030_anti_vacuity_floor.rq").read_text(encoding="utf-8")
    rows = list(cast(Iterable[tuple], graph.query(gate)))
    if not rows:
        print("VACUOUS GATE: gate 030 did not flip under mutation")
        return False
    print(f"PASS anti-vacuity: gate 030 flipped to {len(rows)} row(s) under mutation")
    return True


def spot_check_generated() -> bool:
    gen = PACK_DIR / "generated" / "margin_envelope.ex"
    if not gen.exists():
        print("VIOLATION generated-spot-check: generated/margin_envelope.ex missing")
        return False
    text = gen.read_text(encoding="utf-8")
    checks = {
        "generated marker": "@generated by ggen" in text,
        "module defined": "defmodule MarginEnvelope" in text,
        "refusal atoms present": all(
            atom in text
            for atom in ("REFUSED_BELOW_FLOOR", "REFUSED_NTE_EXCEEDED",
                         "REFUSED_MISSING_BINDING", "ESCALATE_MULTISIG")
        ),
        "fail-closed clause": ":REFUSED_MISSING_BINDING" in text,
        "multi-sig escalation": "resolve_escalation" in text,
        "positive control rendered": "ENV-001" in text and "250000" in text,
    }
    ok = True
    for name, passed in checks.items():
        print(f"{'PASS' if passed else 'VIOLATION'} generated-spot-check: {name}")
        ok = ok and passed
    if not ok:
        return False

    elixir = shutil.which("elixir")
    if elixir is None:
        print("NOTE: elixir not on PATH; runtime admit/1 evaluation not run")
        return True

    decimal_ebin = None
    for candidate in sorted(Path.home().glob("*/_build*/**/lib/decimal/ebin")):
        if candidate.is_dir():
            decimal_ebin = candidate
            break
    if decimal_ebin is None:
        print("NOTE: no compiled Decimal ebin found; runtime eval not run")
        return True
    print(f"NOTE: using Decimal ebin {decimal_ebin}")

    with tempfile.TemporaryDirectory() as td:
        script = Path(td) / "spot.exs"
        script.write_text(
            text
            + "\ndefmodule MarginEnvelopeSpotCheck do\n"
            "  def run do\n"
            '    env = %MarginEnvelope{envelope_id: "ENV-001", '
            'nte: Decimal.new("250000"), quote: Decimal.new("180000"), '
            'floor: Decimal.new("0.22"), currency: "USD"}\n'
            "    IO.puts(elem(MarginEnvelope.admit(env), 0))\n"
            "    IO.puts(MarginEnvelope.margin(env) |> Decimal.to_string())\n"
            '    below = %{env | quote: Decimal.new("220000")}\n'
            "    IO.puts(elem(MarginEnvelope.admit(below), 0))\n"
            "  end\n"
            "end\n"
            "MarginEnvelopeSpotCheck.run()\n",
            encoding="utf-8",
        )

        result = subprocess.run(
            [elixir, "-pa", str(decimal_ebin), str(script)],
            capture_output=True, text=True, timeout=120
        )
        if result.returncode != 0:
            print("VIOLATION elixir-eval: generated module failed to run")
            print(result.stderr)
            return False
        lines = [l for l in result.stdout.splitlines() if l.strip()]
        print(f"PASS elixir-eval: {lines}")
        return lines[:3] == ["admit", "0.28", "escalate"]


def main() -> int:
    graph = Graph()
    graph.parse(ONT, format="turtle")
    v = run_gates(graph)
    if v:
        print(f"FAIL: {v} violation row(s) on the unmutated graph")
        return 1
    if not anti_vacuity_court():
        return 1
    if not spot_check_generated():
        return 1
    print("PASS: gates clean, anti-vacuity flips, generated module verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
