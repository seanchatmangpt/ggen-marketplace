#!/usr/bin/env python3
"""Chicago verifier for trade-reticle-plumbing.

1. Run every gates/*.rq SELECT against ontology.ttl; rows = violation; exit 1
   on any violation.
2. Anti-vacuity court: mutate the graph (delete the positive control's
   camera_inspection_footage_id provision) and PROVE gate 030 flips to
   violation. A gate that cannot flip fails the verifier as VACUOUS GATE.
3. Spot-check the generated module: exists, carries the generated marker,
   names every refusal atom, and a real `elixir` evaluation of
   prior_verdict/2 on the positive control admits; the same drain claim with
   camera footage removed is challenged demanding exactly
   camera_inspection_footage_id; an unknown claim type refuses typed.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Iterable, cast

from rdflib import Graph, Literal, URIRef
from rdflib.namespace import XSD

PACK_DIR = Path(__file__).resolve().parent
ONT = PACK_DIR / "ontology.ttl"
TR = "urn:trade:reticle:plumbing:"


def run_gates(graph: Graph) -> int:
    violations = 0
    for gate in sorted((PACK_DIR / "gates").glob("*.rq")):
        query = gate.read_text(encoding="utf-8")
        rows = list(cast(Iterable[tuple], graph.query(query)))
        if rows:
            violations += len(rows)
            print(f"VIOLATION {gate.name}: {len(rows)} row(s)")
            for row in rows:
                print(f"  {tuple(str(c) for c in row)}")
        else:
            print(f"PASS {gate.name}: 0 rows")
    return violations


def anti_vacuity_court() -> bool:
    """Mutate: delete camera_inspection_footage_id from the positive control's
    providedTelemetry. Gate 030 (telemetry coverage law) MUST flip to >= 1 row."""
    graph = Graph()
    graph.parse(ONT, format="turtle")
    subject = URIRef(TR + "claim-drain-001")
    predicate = URIRef(TR + "providedTelemetry")
    obj = Literal("camera_inspection_footage_id")

    mutated = 0
    for s, p, o in list(graph.triples((subject, predicate, None))):
        if str(o) == "camera_inspection_footage_id":
            graph.remove((s, p, o))
            mutated += 1
    if mutated == 0:
        print("VACUOUS COURT: mutation target not found; mutation never ran")
        return False

    gate = (PACK_DIR / "gates" / "030_telemetry_coverage_law.rq").read_text(encoding="utf-8")
    rows = list(cast(Iterable[tuple], graph.query(gate)))
    if not rows:
        print("VACUOUS GATE: gate 030 did not flip under mutation")
        return False
    print(f"PASS anti-vacuity: gate 030 flipped to {len(rows)} row(s) under mutation")
    return True


def spot_check_generated() -> bool:
    gen = PACK_DIR / "generated" / "trade_reticle_plumbing.ex"
    if not gen.exists():
        print("VIOLATION generated-spot-check: generated/trade_reticle_plumbing.ex missing")
        return False
    text = gen.read_text(encoding="utf-8")
    checks = {
        "generated marker": "@generated by ggen" in text,
        "module defined": "defmodule TradeReticle.Plumbing" in text,
        "behaviour declared": "@behaviour AshA2A.Twin.MechanicalPrior" in text,
        "refusal atoms present": all(
            atom in text
            for atom in ("REFUSED_UNKNOWN_CLAIM_TYPE", "REFUSED_MISSING_TELEMETRY",
                         "REFUSED_NO_PRIOR")
        ),
        "positive control rendered": "camera_inspection_footage_id" in text
        and "drain_line_replacement" in text,
    }
    ok = True
    for name, passed in checks.items():
        print(f"{'PASS' if passed else 'VIOLATION'} generated-spot-check: {name}")
        ok = ok and passed
    if not ok:
        return False

    elixir = shutil.which("elixir")
    if elixir is None:
        print("NOTE: elixir not on PATH; runtime prior_verdict/2 evaluation not run")
        return True

    # vince.ex lives in ash_a2a (behaviour source); compile it alongside the
    # generated module so the @behaviour check is real, not decorative.
    vince = Path.home() / "ash_a2a" / "lib" / "ash_a2a" / "twin" / "vince.ex"
    preamble = ""
    if vince.exists():
        preamble = vince.read_text(encoding="utf-8") + "\n"
    else:
        print("NOTE: vince.ex not found; compiling against the documented contract")

    with tempfile.TemporaryDirectory() as td:
        script = Path(td) / "spot.exs"
        script.write_text(
            preamble
            + text
            + "\n"
            + "prior = TradeReticle.Plumbing\n"
            + 'full = %{"camera_inspection_footage_id" => "CAM-42", '
            + '"pipe_diameter_reading" => "4in", "depth_reading" => "6ft"}\n'
            + 'partial = %{"pipe_diameter_reading" => "4in", "depth_reading" => "6ft"}\n'
            + "IO.inspect(prior.prior_verdict(\"drain_line_replacement\", full))\n"
            + "IO.inspect(prior.prior_verdict(\"drain_line_replacement\", partial))\n"
            + "IO.inspect(prior.prior_verdict(\"deck_recoat\", %{}))\n"
            + "IO.inspect(TradeReticle.Plumbing.refusals())\n",
            encoding="utf-8",
        )

        result = subprocess.run(
            [elixir, str(script)], capture_output=True, text=True, timeout=120
        )
        if result.returncode != 0:
            print("VIOLATION elixir-eval: generated module failed to run")
            print(result.stderr)
            return False
        out = result.stdout
        checks = {
            "admit on complete telemetry": "admit" in out
            and 'claim_type: "drain_line_replacement"' in out,
            "challenge demands camera footage": "camera_inspection_footage_id" in out
            and "challenge" in out,
            "typed refuse on unknown claim type": "unknown_claim_type" in out
            and "deck_recoat" in out,
            "closed refusal vocabulary": "REFUSED_NO_PRIOR" in out,
        }
        ok = True
        for name, passed in checks.items():
            print(f"{'PASS' if passed else 'VIOLATION'} elixir-eval: {name}")
            ok = ok and passed
        return ok


def main() -> int:
    graph = Graph()
    graph.parse(ONT, format="turtle")
    v = run_gates(graph)
    if v:
        print(f"FAIL: {v} violation row(s) on the unmutated graph")
        return 1
    if not anti_vacuity_court():
        return 1
    if not spot_check_generated():
        return 1
    print("PASS: gates clean, anti-vacuity flips, generated module verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
