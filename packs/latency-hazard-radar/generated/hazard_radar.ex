defmodule LatencyHazard.HazardRadar do
  @moduledoc """
  GENERATED by latency-hazard-radar from urn:latency-hazard-radar: — do not edit by hand.

  Response-latency hazard radar: robust median (tilde-mu) / MAD estimation over
  an observation window, hazard Z-score Z = (t_elapsed - median) / MAD, and
  triage-prompt emission when the Z-score exceeds the hazard threshold.

  Typed outcomes: `{:ok, map()}` with the estimated statistics, or
  `{:error, :insufficient_dispersion}` when MAD = 0 (zero-dispersion window).
  """

  @hazard_threshold 2.5
  @refusal_atom :insufficient_dispersion
  @triage_prompt "HAZARD: response latency exceeded robust hazard threshold; triage required"
  @median_witness 105
  @mad_witness 7

  @doc "Hazard threshold (Z-score above which triage trips)."
  def hazard_threshold, do: @hazard_threshold

  @doc "Typed atom returned when the window has zero dispersion (MAD = 0)."
  def refusal_atom, do: @refusal_atom

  @doc "Triage-prompt event text emitted on hazard trip."
  def triage_prompt, do: @triage_prompt

  @doc """
  Observe a response latency against an observation window.

      observe(t_elapsed, window, operation \\ "op")

  Returns `{:ok, %{z: z, median: m, mad: d, trip?: bool}}` or
  `{:error, :insufficient_dispersion}`.
  """
  @spec observe(number(), [number()], String.t() | atom()) ::
          {:ok, map()} | {:error, :insufficient_dispersion}
  def observe(t_elapsed, window, operation \\ "op") when is_number(t_elapsed) and is_list(window) do
    case zscore(t_elapsed, window) do
      {:ok, z} ->
        {:ok,
         %{
           operation: operation,
           z: z,
           median: median(window),
           mad: mad(window),
           trip?: trip?(z, @hazard_threshold)
         }}

      {:error, _} = err ->
        err
    end
  end

  @doc """
  Hazard Z-score: Z = (t_elapsed - median(window)) / MAD(window).

  Returns `{:error, :insufficient_dispersion}` when MAD = 0.
  """
  @spec zscore(number(), [number()]) :: {:ok, float()} | {:error, :insufficient_dispersion}
  def zscore(t_elapsed, window) when is_number(t_elapsed) and is_list(window) do
    case mad(window) do
      0.0 -> {:error, :insufficient_dispersion}
      d -> {:ok, (t_elapsed - median(window)) / d}
    end
  end

  @doc "Triage decision: true when z exceeds the hazard threshold (strictly greater)."
  @spec trip?(number(), number()) :: boolean()
  def trip?(z, threshold \\ @hazard_threshold) when is_number(z) and is_number(threshold) do
    z > threshold
  end

  @doc "Median of a numeric list (average of the two middle values for even length)."
  @spec median([number()]) :: float()
  def median([]), do: raise(ArgumentError, "median of empty window")
  def median(list) do
    sorted = Enum.sort(list)
    n = length(sorted)
    if rem(n, 2) == 1 do
      Enum.at(sorted, div(n, 2)) * 1.0
    else
      (Enum.at(sorted, div(n, 2) - 1) + Enum.at(sorted, div(n, 2))) / 2
    end
  end

  @doc "Median absolute deviation of a numeric list (0.0 for an empty or zero-dispersion window)."
  @spec mad([number()]) :: float()
  def mad([]), do: 0.0
  def mad(list) do
    m = median(list)
    list |> Enum.map(fn x -> abs(x - m) end) |> median()
  end
end
