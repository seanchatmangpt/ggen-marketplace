#!/usr/bin/env python3
"""Chicago verifier for challenger-sales-cscb.

1. Run every gates/*.rq SELECT against ontology.ttl; rows = violation; exit 1
   on any violation.
2. Anti-vacuity court: mutate the graph (drop ONE mapsToLoss triple from the
   rational-drowning stage) and PROVE gate 030 flips to violation. A gate that
   cannot flip fails the verifier as VACUOUS GATE.
3. SHACL-validate the graph against shapes.ttl (pyshacl when available; NOTE
   and skip when not installed).
4. Spot-check the generated module: it exists, carries the generated marker,
   names every verdict atom in the closed vocabulary, and has fail-closed
   clauses.
"""
import re
import shutil
import sys
from pathlib import Path
from typing import Iterable, cast

from rdflib import Graph, Literal, URIRef

PACK_DIR = Path(__file__).resolve().parent
ONT = PACK_DIR / "ontology.ttl"


def run_gates(graph: Graph) -> int:
    violations = 0
    for gate in sorted((PACK_DIR / "gates").glob("*.rq")):
        query = gate.read_text(encoding="utf-8")
        rows = list(cast(Iterable[tuple], graph.query(query)))
        if rows:
            violations += len(rows)
            print(f"VIOLATION {gate.name}: {len(rows)} row(s)")
            for row in rows:
                print(f"  {tuple(str(c) for c in row)}")
        else:
            print(f"PASS {gate.name}: 0 rows")
    return violations


def shacl_validate(graph: Graph) -> bool:
    try:
        from pyshacl import validate as pyshacl_validate
    except ImportError:
        print("NOTE: pyshacl not installed; SHACL validation not run")
        return True
    shapes = Graph()
    shapes.parse(PACK_DIR / "shapes.ttl", format="turtle")
    conforms, _, report_text = pyshacl_validate(
        graph, shacl_graph=shapes, inference="rdfs", advanced=True)
    if conforms:
        print("PASS shacl: graph conforms to shapes.ttl")
        return True
    print("VIOLATION shacl: graph does NOT conform")
    print(report_text)
    return False


def anti_vacuity_court() -> bool:
    """Mutate: drop ONE mapsToLoss triple (ma-002, 45000) from the
    rational-drowning stage. Loss sum drops 195000 -> 150000 while the declared
    annualDollarHemorrhage stays 195000, so gate 030 MUST flip to >= 1 row."""
    graph = Graph()
    graph.parse(ONT, format="turtle")
    target = URIRef("urn:cscb:ma-002")
    pred = URIRef("urn:cscb:mapsToLoss")
    mutated = 0
    for s, p, o in graph.triples((target, pred, None)):
        graph.remove((s, p, o))
        mutated += 1
    if mutated == 0:
        print("VACUOUS COURT: mutation target not found; mutation never ran")
        return False

    gate = (PACK_DIR / "gates" / "030_anti_vacuity_mapsToLoss.rq").read_text(
        encoding="utf-8")
    rows = list(cast(Iterable[tuple], graph.query(gate)))
    if not rows:
        print("VACUOUS GATE: gate 030 did not flip under mutation")
        return False
    print(f"PASS anti-vacuity: gate 030 flipped to {len(rows)} row(s) under mutation")
    return True


def spot_check_generated() -> bool:
    gen = PACK_DIR / "generated" / "arc_verdict.ex"
    if not gen.exists():
        print("VIOLATION generated-spot-check: generated/arc_verdict.ex missing")
        return False
    text = gen.read_text(encoding="utf-8")
    checks = {
        "generated marker": "@generated by ggen" in text,
        "module defined": "defmodule ArcVerdict" in text,
        "verdict atoms present": all(
            atom in text
            for atom in ("STATUS_QUO_REFUSED", "ADOPTED", "INCONCLUSIVE")
        ),
        "fail-closed clauses": (":REFUSED_INVALID_VERDICT" in text
                                and ":REFUSED_LOSS_MISMATCH" in text
                                and ":REFUSED_MISSING_BINDING" in text),
        "positive control rendered": "run-001" in text and "195000" in text,
    }
    ok = True
    for name, passed in checks.items():
        print(f"{'PASS' if passed else 'VIOLATION'} generated-spot-check: {name}")
        ok = ok and passed
    return ok


def label_injection_court() -> bool:
    """AR6 P0 anti-vacuity (R15): inject a hostile ArcStage label
    (`Health"; drop table; //` and a 10MB label) into a COPY of the graph and
    PROVE gate 040 flips to violation. A gate that cannot flip fails the
    verifier as VACUOUS GATE."""
    gate = (PACK_DIR / "gates" / "040_label_safety.rq").read_text(encoding="utf-8")
    ok = True
    for name, hostile in (
        ("quote+newline label", 'Health"; let x : u32 = 0; //'),
        ("10MB label", "A" * 10 * 1024 * 1024),
    ):
        graph = Graph()
        graph.parse(ONT, format="turtle")
        stage = URIRef("urn:cscb:S1")
        RDFS_LABEL = URIRef("http://www.w3.org/2000/01/rdf-schema#label")
        graph.remove((stage, RDFS_LABEL, None))
        graph.add((stage, RDFS_LABEL, Literal(hostile)))
        rows = list(cast(Iterable[tuple], graph.query(gate)))
        if not rows:
            print(f"VACUOUS GATE: gate 040 did not flip under {name}")
            ok = False
        else:
            print(f"PASS label-injection court: gate 040 flipped under {name} "
                  f"({len(rows)} row(s))")
    return ok


def spot_check_emitted_rust_labels() -> bool:
    """AR6 defense-in-depth proof (R15): every stage name literal emitted into
    emitted_rust/src/main.rs must (a) contain no quote, backslash, or control
    byte, (b) match an ontology ArcStage label exactly."""
    main_rs = PACK_DIR / "emitted_rust" / "src" / "main.rs"
    if not main_rs.exists():
        print("VIOLATION emitted-label-spot-check: emitted_rust/src/main.rs missing")
        return False
    text = main_rs.read_text(encoding="utf-8")
    graph = Graph()
    graph.parse(ONT, format="turtle")
    # Stage labels re-derived from the ontology: subjects typed as ArcStage
    # subclasses.
    q = graph.query("""
        PREFIX cscb: <urn:cscb:>
        PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
        SELECT ?l WHERE {
            ?stage a/rdfs:subClassOf* cscb:ArcStage ; rdfs:label ?l .
        }
    """)
    labels = {str(row[0]) for row in q}
    emitted = []
    for line in text.splitlines():
        m = re.match(r'^\("(.*)", \d+\),$', line.strip())
        if m:
            emitted.append(m.group(1))
    if len(emitted) != 6:
        print(f"VIOLATION emitted-label-spot-check: expected 6 stage literals, "
              f"found {len(emitted)}")
        return False
    ok = True
    for name in emitted:
        if any(c in name for c in ('"', '\\')) or any(ord(c) < 0x20 for c in name):
            print(f"VIOLATION emitted-label-spot-check: hostile bytes in "
                  f"emitted stage literal: {name!r}")
            ok = False
        if name not in labels:
            print(f"VIOLATION emitted-label-spot-check: emitted stage name "
                  f"{name!r} is not an ontology ArcStage label")
            ok = False
    if ok:
        print(f"PASS emitted-label-spot-check: {len(emitted)} stage literals, "
              f"no hostile bytes, all ontology-matched")
    return ok


def orphan_stage_court() -> bool:
    """AR6 P1 anti-vacuity (R15): add a typed ArcStage never bound to any arc
    and PROVE gate 050 flips to violation."""
    gate = (PACK_DIR / "gates" / "050_orphan_stage.rq").read_text(encoding="utf-8")
    graph = Graph()
    graph.parse(ONT, format="turtle")
    graph.add((URIRef("urn:cscb:S7"),
               URIRef("http://www.w3.org/1999/02/22-rdf-syntax-ns#type"),
               URIRef("urn:cscb:ArcStage")))
    rows = list(cast(Iterable[tuple], graph.query(gate)))
    if not rows:
        print("VACUOUS GATE: gate 050 did not flip under orphan-stage injection")
        return False
    print(f"PASS orphan-stage court: gate 050 flipped under rogue stage "
          f"({len(rows)} row(s))")
    return True


def main() -> int:
    graph = Graph()
    graph.parse(ONT, format="turtle")
    v = run_gates(graph)
    if v:
        print(f"FAIL: {v} violation row(s) on the unmutated graph")
        return 1
    if not shacl_validate(graph):
        return 1
    if not anti_vacuity_court():
        return 1
    if not spot_check_generated():
        return 1
    if not label_injection_court():
        return 1
    if not orphan_stage_court():
        return 1
    if not spot_check_emitted_rust_labels():
        return 1
    print("PASS: gates clean, SHACL conforms (if available), anti-vacuity flips, "
          "generated module verified, label-injection court flips, "
          "emitted Rust labels clean")
    return 0


if __name__ == "__main__":
    sys.exit(main())
